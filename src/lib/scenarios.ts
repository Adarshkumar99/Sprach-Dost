/** one node of a branching role-play story graph */
export type BranchNode = {
  id: string;
  /** short English situation update — shown to the student and injected into the prompt */
  situation: string;
  /** what the German-speaking partner tries to achieve in this node */
  npcGoal: string;
  /** transitions based on how well the student handled the node */
  outcomes: { on: "good" | "bad"; next: string }[];
  final?: boolean;
};

export type Scenario = {
  id: string;
  title: string;
  icon: string;
  category: string;
  level: "A1" | "A2" | "B1" | "B2";
  description: string;
  /** exact situation briefing injected into the AI system prompt */
  goal: string;
  /** German words the partner should naturally introduce */
  vocab: string[];
  /** opening hint for the student */
  opener: string;
  /** career pack this scenario belongs to (optional) */
  track?: "nursing" | "it" | "ausbildung";
  /** branching story graph (optional — generated by scripts/generate-branches.mjs) */
  branches?: BranchNode[];
};

